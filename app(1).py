# OPTIONAL HOURLY ANALYSIS
# ============================================================
if hourly_steps_file is not None or hourly_cal_file is not None:
    st.divider()
    st.subheader("⏰ Hourly Activity Profile")

    hourly_parts = []

    if hourly_steps_file is not None:
        hs = load_optional_csv(hourly_steps_file, "ActivityHour")

        if "ActivityHour" in hs.columns and "StepTotal" in hs.columns:
            hs["Hour"] = hs["ActivityHour"].dt.hour
            hs_hour = (
                hs.groupby("Hour", as_index=False)["StepTotal"]
                .mean()
                .rename(columns={"StepTotal": "AvgSteps"})
            )
            hourly_parts.append(hs_hour)

    if hourly_cal_file is not None:
        hc = load_optional_csv(hourly_cal_file, "ActivityHour")

        if "ActivityHour" in hc.columns and "Calories" in hc.columns:
            hc["Hour"] = hc["ActivityHour"].dt.hour
            hc_hour = (
                hc.groupby("Hour", as_index=False)["Calories"]
                .mean()
                .rename(columns={"Calories": "AvgCalories"})
            )
            hourly_parts.append(hc_hour)

    if hourly_parts:
        hourly_df = hourly_parts[0]

        for part in hourly_parts[1:]:
            hourly_df = hourly_df.merge(part, on="Hour", how="outer")

        fig = go.Figure()

        if "AvgSteps" in hourly_df.columns:
            fig.add_trace(
                go.Scatter(
                    x=hourly_df["Hour"],
                    y=hourly_df["AvgSteps"],
                    mode="lines+markers",
                    name="Average Steps"
                )
            )

        if "AvgCalories" in hourly_df.columns:
            fig.add_trace(
                go.Scatter(
                    x=hourly_df["Hour"],
                    y=hourly_df["AvgCalories"],
                    mode="lines+markers",
                    name="Average Calories",
                    yaxis="y2"
                )
            )

        fig.update_layout(
            title="Average Steps and Calories by Hour",
            xaxis=dict(
                title="Hour of Day",
                tickmode="linear",
                dtick=1
            ),
            yaxis=dict(title="Average Steps"),
            yaxis2=dict(
                title="Average Calories",
                overlaying="y",
                side="right"
            ),
            height=500
        )

        st.plotly_chart(fig, use_container_width=True)


