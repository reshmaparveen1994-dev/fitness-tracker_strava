# ---------- Filters ----------
st.sidebar.header("🔎 Filters")

# Date filter
min_date = daily["Date"].min()
max_date = daily["Date"].max()

if pd.notna(min_date) and pd.notna(max_date):
    date_range = st.sidebar.date_input(
        "Date range",
        value=(min_date.date(), max_date.date()),
        min_value=min_date.date(),
        max_value=max_date.date()
    )

    if isinstance(date_range, tuple) and len(date_range) == 2:
        start_date, end_date = date_range
        filtered = daily[
            (daily["Date"].dt.date >= start_date) &
            (daily["Date"].dt.date <= end_date)
        ].copy()
    else:
        filtered = daily.copy()
else:
    filtered = daily.copy()

# Activity level filter
if "ActivityLevel" in daily.columns:
    levels = sorted(daily["ActivityLevel"].dropna().astype(str).unique())
    selected_levels = st.sidebar.multiselect(
        "Activity level",
        levels,
        default=levels
    )
    filtered = filtered[
        filtered["ActivityLevel"].astype(str).isin(selected_levels)
    ]

# User filter
if "Id" in daily.columns:
    user_ids = sorted(daily["Id"].dropna().astype(str).unique())
    selected_users = st.sidebar.multiselect(
        "User ID",
        user_ids,
        default=[],
        help="Leave empty to include all users."
    )

    if selected_users:
        filtered = filtered[
            filtered["Id"].astype(str).isin(selected_users)
        ]

if filtered.empty:
    st.warning("No data matches the selected filters.")
    st.stop()


